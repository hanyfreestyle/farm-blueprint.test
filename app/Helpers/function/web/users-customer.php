if (!function_exists('activeProfileMenu')) {
  function activeProfileMenu($pageView, $selMenu): string {
    if (isset($pageView['profileMenu'])) {
      if ($pageView['profileMenu'] == $selMenu) {
        $setActive = 'active';
      } else {
        $setActive = '';
      }
    } else {
      $setActive = '';
    }
    return $setActive;
  }
}

